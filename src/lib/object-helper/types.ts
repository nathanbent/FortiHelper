/** Fill unspecified options with the Python-equivalent defaults. */
export function withDefaults(options: Partial<ObjectHelperOptions> = {}): ObjectHelperOptions {
  return { ...DEFAULT_OPTIONS, ...options };
}

export interface ObjectHelperStats {
  writtenFqdn: number;
  writtenIp: number;
  writtenDirectIp: number;
  writtenIpRange: number;
  skipped: number;
  duplicates: number;
  dnsFailures: number;
  total: number;
  resolvedAt: string;
}

export interface GenerateResult {
  output: string;
  warnings: Warning[];
  stats: ObjectHelperStats;
}

/** Current UTC time formatted like the Python RESOLVED_AT ("YYYY-MM-DD HH:MM:SSZ"). */
export function defaultResolvedAt(now: Date = new Date()): string {
  const p = (n: number) => String(n).padStart(2, '0');
  return (
    `${now.getUTCFullYear()}-${p(now.getUTCMonth() + 1)}-${p(now.getUTCDate())} ` +
    `${p(now.getUTCHours())}:${p(now.getUTCMinutes())}:${p(now.getUTCSeconds())}Z`
  );
}
