/** FortiGate address object name hard limit. */
export const MAX_OBJ_NAME_LEN = 79;

/**
 * DNS resolution results injected into `generateObjects`:
 * fqdn -> list of IPv4 addresses, or an error marker.
 */
export type DnsResults = Record<string, string[] | { error: string }>;

/**
 * All options for the Object Helper generator. Field names and defaults
 * mirror the `Config` dataclass of `input-ideas/object-helper-v3.py`.
 */
export interface ObjectHelperOptions {
  // --- Object name prefix ---
  enablePrefix: boolean;
  namePrefix: string;
  namePrefixDelim: string;

  // --- What to emit ---
  outputFqdnObjects: boolean;
  outputIpObjects: boolean;

  // --- Groups ---
  enableAllObjectsGroup: boolean;
  allObjectsGroupName: string;
  enablePerFqdnGroup: boolean;

  // --- Object appearance ---
  enableComment: boolean;
  commentTemplateFqdn: string;
  commentTemplateIp: string;
  commentTemplateDirectIp: string;
  /**
   * Text added to every address object's comment. Appended after whatever
   * comment the entry already has, or used on its own when it has none.
   * Empty disables it. Requires `enableComment`.
   */
  bulkComment: string;
  /** Joins an existing comment and `bulkComment`. */
  bulkCommentSeparator: string;
  enableColor: boolean;
  colorId: number;

  // --- Input format ---
  useExplicitNames: boolean;
  useInputComment: boolean;
  nameFqdnDelimiter: string;
  lowercaseFqdn: boolean;

  // --- Extra object options ---
  enableAllowRouting: boolean;
  enableFabricObject: boolean;
  enablePassiveFqdnLearning: boolean;
  enableCacheTtl: boolean;
  cacheTtlSeconds: number;
  enableAssociatedInterface: boolean;
  associatedInterface: string;

  // --- Output structure ---
  startWithConfigFirewallAddress: boolean;
  endConfigFirewallAddress: boolean;

  // --- DNS resolution ---
  maxIpsPerFqdn: number;
  dnsTimeoutSeconds: number;
  dnsWorkers: number;

  // --- Direct IP / CIDR object naming ---
  ipCidrSeparator: string;

  // --- Resolved IP object naming ---
  ipObjectsUseIndex: boolean;
  ipObjectSuffix: string;

  // --- Group details ---
  perFqdnGroupSuffix: string;
  enableGroupComment: boolean;
  groupCommentTemplate: string;
  enableGroupColor: boolean;
  groupColorId: number;
  enableGroupType: boolean;
  groupType: string;
  enableGroupCategory: boolean;
  groupCategory: string;
  enableGroupFabricObject: boolean;

  /**
   * Timestamp used for the {resolved_at} placeholder, formatted
   * "YYYY-MM-DD HH:MM:SSZ". Injectable for deterministic tests;
   * defaults to the current UTC time.
   */
  resolvedAt?: string;
}

