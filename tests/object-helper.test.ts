describe('resolveFqdns (mocked fetch)', () => {
  afterEach(() => {
    vi.unstubAllGlobals();
  });

  function dohResponse(body: unknown, ok = true, status = 200): Response {
    return {
      ok,
      status,
      json: async () => body,
    } as unknown as Response;
  }

  it('returns sorted unique capped A records from Cloudflare', async () => {
    const fetchMock = vi.fn().mockResolvedValue(
      dohResponse({
        Status: 0,
        Answer: [
          { type: 1, data: '9.9.9.9' },
          { type: 1, data: '1.1.1.1' },
          { type: 1, data: '9.9.9.9' },
          { type: 5, data: 'cname.example.com.' },
        ],
      }),
    );
    vi.stubGlobal('fetch', fetchMock);
    const results = await resolveFqdns(['example.com'], { maxIps: 20 });
    expect(results['example.com']).toEqual(['1.1.1.1', '9.9.9.9']);
    expect(fetchMock).toHaveBeenCalledTimes(1);
    expect(String(fetchMock.mock.calls[0][0])).toContain('cloudflare-dns.com');
  });

  it('falls back to Google when Cloudflare fails', async () => {
    const fetchMock = vi
      .fn()
      .mockResolvedValueOnce(dohResponse({}, false, 500))
      .mockResolvedValueOnce(dohResponse({ Status: 0, Answer: [{ type: 1, data: '8.8.8.8' }] }));
    vi.stubGlobal('fetch', fetchMock);
    const results = await resolveFqdns(['example.com']);
    expect(results['example.com']).toEqual(['8.8.8.8']);
    expect(String(fetchMock.mock.calls[1][0])).toContain('dns.google');
  });

  it('records an error entry when both endpoints fail', async () => {
    const fetchMock = vi.fn().mockResolvedValue(dohResponse({ Status: 3 }));
    vi.stubGlobal('fetch', fetchMock);
    const results = await resolveFqdns(['nxdomain.example.com']);
    expect(results['nxdomain.example.com']).toEqual({ error: 'DNS error status 3' });
  });
});
