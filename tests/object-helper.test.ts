describe('duplicate suppression', () => {
  it('suppresses repeated names across entry types and counts them', () => {
    const input = 'example.com\nexample.com\n10.0.0.1\n10.0.0.1\n';
    const { output, stats, warnings } = generateObjects(input);
    expect(stats.duplicates).toBe(2);
    expect(stats.total).toBe(2);
    expect((output.match(/edit "Prefix-example\.com"/g) ?? []).length).toBe(1);
    expect(warnings.filter((w) => w.message.includes('Duplicate object name'))).toHaveLength(2);
    expect(warnings.find((w) => w.message === "Duplicate object name skipped: 'Prefix-example.com'")?.line).toBe(2);
  });

  it('suppresses a direct IP colliding with an explicit name', () => {
    const input = 'same\nexample.com\nsame\n10.0.0.1\n';
    const { stats } = generateObjects(input, { useExplicitNames: true });
    expect(stats.duplicates).toBe(1);
    expect(stats.total).toBe(1);
  });
});

