describe('tryParseIpNetwork', () => {
  it('parses bare IPs as /32', () => {
    expect(tryParseIpNetwork('10.0.0.5')).toEqual({
      networkAddress: '10.0.0.5',
      netmask: '255.255.255.255',
      prefixlen: 32,
    });
  });

  it('masks off host bits (strict=false)', () => {
    expect(tryParseIpNetwork('10.0.0.1/24')).toEqual({
      networkAddress: '10.0.0.0',
      netmask: '255.255.255.0',
      prefixlen: 24,
    });
  });

  it('accepts netmask and hostmask notation', () => {
    expect(tryParseIpNetwork('10.30.0.0/255.255.255.0')?.prefixlen).toBe(24);
    expect(tryParseIpNetwork('10.30.0.0/0.0.0.255')?.prefixlen).toBe(24);
  });

  it('accepts /0 and /32', () => {
    expect(tryParseIpNetwork('0.0.0.0/0')).toEqual({
      networkAddress: '0.0.0.0',
      netmask: '0.0.0.0',
      prefixlen: 0,
    });
    expect(tryParseIpNetwork('255.255.255.255/32')?.networkAddress).toBe('255.255.255.255');
  });

  it('rejects anything containing a hyphen (ranges)', () => {
    expect(tryParseIpNetwork('10.0.0.1-10.0.0.9')).toBeNull();
  });

  it('rejects invalid addresses, prefixes, and masks', () => {
    expect(tryParseIpNetwork('10.0.0.999')).toBeNull();
    expect(tryParseIpNetwork('10.0.0')).toBeNull();
    expect(tryParseIpNetwork('10.0.0.0.1')).toBeNull();
    expect(tryParseIpNetwork('10.0.0.0/33')).toBeNull();
    expect(tryParseIpNetwork('10.0.0.0/')).toBeNull();
    expect(tryParseIpNetwork('010.0.0.1')).toBeNull(); // leading zero octet
    expect(tryParseIpNetwork('1.2.3.04')).toBeNull();
    expect(tryParseIpNetwork('10.0.0.0/255.0.255.0')).toBeNull(); // non-contiguous
    expect(tryParseIpNetwork('2001:db8::/32')).toBeNull(); // IPv6 not supported
    expect(tryParseIpNetwork('example.com')).toBeNull();
  });

  it('allows leading zeros in the prefix length like Python', () => {
    expect(tryParseIpNetwork('10.0.0.0/024')?.prefixlen).toBe(24);
  });
});

describe('tryParseIpRange', () => {
  it('parses full start-end ranges', () => {
    expect(tryParseIpRange('10.0.0.1-10.0.0.9')).toEqual({ start: '10.0.0.1', end: '10.0.0.9' });
    expect(tryParseIpRange(' 10.0.0.1 - 10.0.0.9 ')).toEqual({
      start: '10.0.0.1',
      end: '10.0.0.9',
    });
  });

  it('parses last-octet shorthand', () => {
    expect(tryParseIpRange('10.0.0.1-9')).toEqual({ start: '10.0.0.1', end: '10.0.0.9' });
    expect(tryParseIpRange('172.16.0.30-40')).toEqual({ start: '172.16.0.30', end: '172.16.0.40' });
    expect(tryParseIpRange('10.0.0.1-255')).toEqual({ start: '10.0.0.1', end: '10.0.0.255' });
  });

  it('allows start == end', () => {
    expect(tryParseIpRange('10.0.0.5-10.0.0.5')).toEqual({ start: '10.0.0.5', end: '10.0.0.5' });
  });

  it('rejects reversed ranges', () => {
    expect(tryParseIpRange('10.0.0.9-10.0.0.1')).toBeNull();
    expect(tryParseIpRange('10.0.0.50-45')).toBeNull();
  });

  it('rejects invalid endpoints', () => {
    expect(tryParseIpRange('10.0.0.1-999')).toBeNull();
    expect(tryParseIpRange('10.0.0.1-009')).toBeNull(); // leading-zero octet after substitution
    expect(tryParseIpRange('example.com-thing')).toBeNull();
    expect(tryParseIpRange('10.0.0.1')).toBeNull(); // no hyphen
  });
});

describe('validateFqdn', () => {
  const opts = { lowercaseFqdn: false };

  it('accepts normal and wildcard FQDNs and strips quotes', () => {
    expect(validateFqdn('example.com', opts)).toBe('example.com');
    expect(validateFqdn('"example.com"', opts)).toBe('example.com');
    expect(validateFqdn("'example.com'", opts)).toBe('example.com');
    expect(validateFqdn('*.cdn.example.net', opts)).toBe('*.cdn.example.net');
  });

  it('lowercases only when asked', () => {
    expect(validateFqdn('ExAmPle.COM', opts)).toBe('ExAmPle.COM');
    expect(validateFqdn('ExAmPle.COM', { lowercaseFqdn: true })).toBe('example.com');
  });

  it('rejects with the exact Python error messages', () => {
    expect(() => validateFqdn('', opts)).toThrow('empty fqdn');
    expect(() => validateFqdn('has space.com', opts)).toThrow('fqdn contains whitespace');
    expect(() => validateFqdn('https://example.org/path', opts)).toThrow(
      'fqdn looks like a URL; provide host only (e.g., example.com)',
    );
    expect(() => validateFqdn('example.com/path', opts)).toThrow(
      'fqdn looks like a URL; provide host only (e.g., example.com)',
    );
    expect(() => validateFqdn('singlelabel', opts)).toThrow(
      'fqdn must contain a dot (e.g., example.com)',
    );
    expect(() => validateFqdn('double..dot.com', opts)).toThrow('fqdn has an empty label (..)');
    expect(() => validateFqdn(`${'a'.repeat(64)}.com`, opts)).toThrow('fqdn label too long (>63)');
    expect(() => validateFqdn('-lead.example.com', opts)).toThrow(
      "fqdn label cannot start/end with '-'",
    );
    expect(() => validateFqdn('trail-.example.com', opts)).toThrow(
      "fqdn label cannot start/end with '-'",
    );
    expect(() => validateFqdn('bad_label.example.com', opts)).toThrow(
      "fqdn label has invalid chars: 'bad_label'",
    );
  });
});

describe('safeObjName', () => {
  it('strips quotes and collapses whitespace', () => {
    const warnings: string[] = [];
    const warn = (m: string) => warnings.push(m);
    expect(safeObjName('  a  "b"\nc  ', warn)).toBe('a b c');
    expect(warnings).toHaveLength(0);
  });

  it('throws on empty names', () => {
    expect(() => safeObjName('  " " ', () => {})).toThrow('empty object name');
  });

  it('warns (but keeps) names over 79 chars', () => {
    const warnings: string[] = [];
    const long = 'x'.repeat(85);
    const result = safeObjName(long, (m) => warnings.push(m));
    expect(result).toBe(long);
    expect(warnings).toEqual([
      `Warning: object name exceeds 79 chars and will be rejected by FortiGate: '${long}'`,
    ]);
  });
});

