describe('bulk comment', () => {
  /** Comment lines emitted for address objects, in output order. */
  function comments(output: string): string[] {
    return [...output.matchAll(/^set comment "(.*)"$/gm)].map((m) => m[1]);
  }

  it('is off by default, leaving output unchanged', () => {
    const input = 'example.com\n';
    expect(generateObjects(input, {}).output).toBe(
      generateObjects(input, { bulkComment: '' }).output,
    );
  });

  it('stands alone when the object has no other comment', () => {
    const { output } = generateObjects('example.com\n', { bulkComment: 'Ticket 123' });
    expect(comments(output)).toContain('Ticket 123');
  });

  it('is appended to an existing input comment', () => {
    const { output } = generateObjects('example.com\nfrom the vendor\n', {
      useInputComment: true,
      bulkComment: 'Ticket 123',
    });
    expect(comments(output)).toContain('from the vendor | Ticket 123');
  });

  it('is appended to a rendered template comment', () => {
    const { output } = generateObjects('example.com\n', {
      commentTemplateFqdn: 'fqdn={fqdn}',
      bulkComment: 'Ticket 123',
    });
    expect(comments(output)).toContain('fqdn=example.com | Ticket 123');
  });

  it('honours a custom separator', () => {
    const { output } = generateObjects('example.com\nvendor\n', {
      useInputComment: true,
      bulkComment: 'Ticket 123',
      bulkCommentSeparator: ' — ',
    });
    expect(comments(output)).toContain('vendor — Ticket 123');
  });

  it('applies to every object in the list', () => {
    const { output } = generateObjects('a.example\nb.example\nc.example\n', {
      bulkComment: 'Ticket 123',
    });
    const found = comments(output).filter((c) => c.includes('Ticket 123'));
    expect(found).toHaveLength(3);
  });

  it('is ignored when comments are disabled', () => {
    const { output } = generateObjects('example.com\n', {
      enableComment: false,
      bulkComment: 'Ticket 123',
    });
    expect(output).not.toContain('set comment');
  });

  it('ignores a whitespace-only value and trims the text', () => {
    expect(generateObjects('example.com\n', { bulkComment: '   ' }).output).not.toContain(
      'set comment',
    );
    const { output } = generateObjects('example.com\n', { bulkComment: '  Ticket 123  ' });
    expect(comments(output)).toContain('Ticket 123');
  });

  it('sanitizes double quotes like other comments', () => {
    const { output } = generateObjects('example.com\n', { bulkComment: 'say "hi"' });
    expect(comments(output)).toContain("say 'hi'");
  });

  it('applies to direct IP and range objects too', () => {
    const { output } = generateObjects('10.0.0.0/24\n10.1.1.1-10.1.1.9\n', {
      bulkComment: 'Ticket 123',
    });
    const found = comments(output).filter((c) => c.includes('Ticket 123'));
    expect(found).toHaveLength(2);
  });
});

